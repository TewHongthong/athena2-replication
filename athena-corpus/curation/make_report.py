#!/usr/bin/env python3
"""Write curation_report.md from <benchmark>/curation_stats.json and the files on disk (numbers are never typed by hand).
Usage: python make_report.py --benchmark <dir>"""
import argparse, collections, glob, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import rules as R

LANGS = ["python", "java", "javascript", "typescript", "csharp"]
NAMES = {"python": "Python", "java": "Java", "javascript": "JavaScript", "typescript": "TypeScript", "csharp": "C#", "cpp": "C++"}


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--benchmark", required=True); a = ap.parse_args()
    B = a.benchmark
    st = json.load(open(os.path.join(B, "curation_stats.json"), encoding="utf-8"))
    snips = {l: [json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(f"{B}/snippets/{l}/*.json"))] for l in LANGS}
    viols = {l: [json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(f"{B}/violations/{l}/*.json"))] for l in LANGS}
    L = []
    w = L.append
    w("# Athena benchmark curation report (Task C, real corpus)\n")
    w(f"Generated by `curation/make_report.py` from `curation_stats.json`. Pipeline `{st['pipeline']}`; ontology "
      f"`athena_ontology.json` sha256 `{st['ontology_sha256'][:16]}…` ({st['ontology_nodes']} nodes / {st['ontology_links']} links).\n")
    tot_s = sum(len(v) for v in snips.values()); tot_v = sum(len(v) for v in viols.values())
    tot_i = sum(len(s["identifiers"]) for v in snips.values() for s in v)
    w(f"## 1. Result\n\n**{tot_s} snippets, {tot_i} target identifiers, {tot_v} injected violations** "
      f"(quota {st['per_language_quota']} snippets per language). Source: the 792-file raw corpus (40 repos, all created after "
      f"2026-06-01, MIT/Apache-2.0). Every snippet is an exact excerpt of a pinned commit; nothing was written or edited by an LLM.\n")
    rows = []
    for l in LANGS:
        ss = snips[l]
        rows.append([NAMES[l], len(ss), sum(len(s["identifiers"]) for s in ss), len(viols[l]),
                     len({s["provenance"]["repo"] for s in ss}), len({s["provenance"]["corpusFile"] for s in ss}),
                     round(sum(s["provenance"]["endLine"] - s["provenance"]["startLine"] + 1 for s in ss) / max(len(ss), 1), 1)])
    rows.append(["**Total**", tot_s, tot_i, tot_v, "", "", ""])
    w(table(["Language", "Snippets", "Identifiers", "Violations", "Repos", "Files", "Avg lines"], rows) + "\n")

    kinds = sorted({i["kind"] for v in snips.values() for s in v for i in s["identifiers"]}, key=lambda k: (k not in R.TARGET_KINDS, k))
    rows = []
    for l in LANGS:
        c = collections.Counter(i["kind"] for s in snips[l] for i in s["identifiers"])
        rows.append([NAMES[l]] + [c.get(k, 0) for k in kinds])
    w("### Identifiers by kind\n\n" + table(["Language"] + kinds, rows) + "\n")

    rows = []
    rc = collections.Counter((v["language"], v["violatedRuleId"]) for l in LANGS for v in viols[l])
    for (l, rid), n in sorted(rc.items(), key=lambda x: (LANGS.index(x[0][0]), -x[1])):
        rows.append([NAMES[l], rid, n])
    w("### Violations by rule\n\n" + table(["Language", "Rule", "Violations"], rows) + "\n")
    mc = collections.Counter(v["injectionMethod"] for l in LANGS for v in viols[l])
    w("Injection methods: " + ", ".join(f"{k} {n}" for k, n in mc.most_common()) + ".\n")

    w("## 2. How snippets were chosen (funnel)\n")
    u = st["units"]
    w(f"Candidate units = top-level functions/classes/interfaces/enums plus each method of a class (all languages, {u['total']} units). "
      f"A unit is dropped when: {u.get('too_short', 0)} shorter than 6 lines; {u.get('too_long', 0)} longer than 40 lines; "
      f"{u.get('noncompliant_identifier', 0)} contain an identifier that fails a core naming rule (the *standard* snippet must be compliant); "
      f"{u.get('fewer_than_2_eligible_targets', 0)} have fewer than 2 renameable target identifiers; "
      f"{u.get('parse_error_in_unit', 0)} overlap a parse error; {u.get('fewer_than_2_targets_with_violation', 0)} yield fewer than 2 targets with a verified violation; "
      f"{u.get('duplicate_code_dropped', 0)} are duplicates of an already chosen snippet.\n")
    tr = st["target_rejects"]
    w("Target identifiers rejected for renaming safety: " + ", ".join(f"{k} {v}" for k, v in sorted(tr.items(), key=lambda x: -x[1])) + ".\n")
    rv = st["rename_verify"]
    w(f"Rename verification: {rv.get('ok', 0)} candidate renames re-parsed with an identical syntax-tree shape; "
      f"{rv.get('shape_changed', 0)} rejected because the shape changed.\n")
    rows = []
    for l in LANGS:
        c = st["candidates"][l]; t = st["selection_tier"][l]
        rows.append([NAMES[l], c["files"], c["clean_candidate_units"], c["files_with_candidates"], c["repos_with_candidates"],
                     len({s["provenance"]["repo"] for s in snips[l]}), t["tier"]])
    w(table(["Language", "Files", "Clean candidate units", "Files with a candidate", "Repos with a candidate", "Repos in final 100", "Cap-relaxation tier (0=none)"], rows) + "\n")
    w("Selection is greedy: prefer snippets that add rarely-seen identifier kinds, at most 2 non-overlapping snippets per file, a per-repo cap "
      "(relaxed in tiers when the pool is small), deterministic tie-breaks. Two runs produce byte-identical output.\n")

    w("## 3. Real-code compliance census (all declarations in the 792 files, before selection)\n")
    w("Share of checked declarations that fail each core rule (`output_validator.check_naming_compliance`, exempt names excluded). "
      "Useful for the paper: it shows how often real, recent open-source code already violates each standard.\n")
    rows = []
    for l in LANGS:
        dc = st["decl_compliance"][l]
        rids = sorted({k.split("|")[0] for k in dc})
        for rid in rids:
            ch, fl = dc.get(rid + "|checked", 0), dc.get(rid + "|failed", 0)
            rows.append([NAMES[l], rid, ch, fl, f"{100 * fl / ch:.1f}%" if ch else "-"])
    w(table(["Language", "Rule", "Checked", "Failed", "Fail rate"], rows) + "\n")

    w("## 4. Rule policy\n")
    w("Core rules (gate + injection targets) per (language, kind) are listed in `curation/rules.py` (`CORE`); each is verified at start-up to be retrievable "
      "from the ontology for that (language, kind) and cross-checked against `graph_loader.get_applicable_rules` (80 pairs, identical). "
      "Rules **not** used as core rules:\n")
    w(table(["Rule", "Reason"], [[k, v] for k, v in R.EXCLUDED.items()]) + "\n")

    w("## 5. Findings and limitations (read before using the numbers)\n")
    used = {rid for (_, rid) in rc}
    present = {(l, i["kind"]) for l in LANGS for sn in snips[l] for i in sn["identifiers"]}
    unused = sorted({rid for ids in R.CORE.values() for rid in ids} - used)
    def has_targets(rid):
        return any(rid in ids and lk in present for lk, ids in R.CORE.items())
    no_kind = [r for r in unused if not has_targets(r)]
    no_viol = [r for r in unused if has_targets(r)]
    param_py = sum(1 for v in viols["python"] if v["violatedRuleId"] == "PEP8-PARAM-SELF-CLS")
    param_js = sum(1 for v in viols["javascript"] if v["violatedRuleId"] == "AIRBNB-PARAM-DESCRIPTIVE")
    w(f"1. **Ontology gap - parameters.** Ontology v1 has no ordinary-parameter casing rule for Python or JavaScript. Python parameters are gated and "
      f"attacked through `PEP8-PARAM-SELF-CLS` (the only parameter rule carrying `casing=snake_case`; {param_py} violation files carry a `ruleCaveat`). "
      f"JavaScript parameters only get the descriptive-name rule ({param_js} files), so a JS parameter named `user_id` counts as compliant. Adding "
      f"`PEP8-PARAM-SNAKE` / `AIRBNB-PARAM-CAMEL` to the ontology would fix both.\n"
      f"2. **Injection types.** The project's `violation_injector.py` only abbreviates for rules with `minLength` and only strips prefixes/suffixes for rules that carry them, "
      f"so the set is casing_swap ({mc.get('casing_swap', 0)}) and forbidden_pattern ({mc.get('forbidden_pattern', 0)}); there are no abbreviation-style violations for "
      f"Python/Java/C#/TypeScript. Core rules with targets but no constructible violation: {', '.join(no_viol) if no_viol else 'none'} (forbidden-prefix / ASCII patterns the injector cannot build). "
      f"Core rules with no snippet of their identifier kind in the final set (kind rare in the pool): {', '.join(no_kind) if no_kind else 'none'}.\n"
      f"3. **Small TypeScript/JavaScript pools.** Only {st['candidates']['typescript']['repos_with_candidates']} TypeScript and "
      f"{st['candidates']['javascript']['repos_with_candidates']} JavaScript repos have clean candidates; most TS files are React components (exempt: PascalCase functions returning JSX are "
      f"not covered by Google TS Style), so TypeScript snippets are dominated by interfaces/properties/variables and contain almost no classes.\n"
      f"4. **Gate strictness.** A snippet is kept only if *every* checked identifier in it passes its core rules, so snippets skew toward code that already follows each standard "
      f"(see section 3 for how often real code does not).\n"
      f"5. **Not extracted:** module/package/namespace names, type parameters, lambda parameters, destructured names, Python `self`/`cls`, dunder names, C# non-public fields "
      f"(no rule in the ontology), Java `static final` fields of non-primitive/String type (deep immutability not decidable), React components, framework-mandated names are kept as real violations.\n"
      f"6. **Rename scope.** Violations rename every occurrence of the identifier inside the snippet (same namespace: local vs member vs type); code-like multi-word names are also rewritten "
      f"in comments/docstrings so the original name does not leak; targets whose name appears in a string literal, a Python f-string expression, or JS/TS shorthand property are not used. "
      f"Because a snippet is an excerpt, references outside it are unknown.\n"
      f"7. **C# booleans.** Following the pilot (`IsConnected` as `boolean_variable`), bool-typed properties/fields/locals use kind `boolean_variable`; they are gated by the boolean rule "
      f"*and* the base kind's rule, but violations only target the boolean rule (the only one retrievable for that kind).\n"
      f"8. **Schema additions.** `standardId` uses the ontology ids (`PEP8`, `GOOGLE_JAVA`, `DOTNET_DESIGN`, `GOOGLE_TS`, `AIRBNB_JS`, as in the pilot code), not the lower-case ids written in benchmark_schema.md. "
      f"Additive fields: snippet `provenance`; violation `occurrencesRenamed`, `commentOccurrencesRenamed`, `ruleCaveat`.\n")

    w("## 6. Checks performed\n")
    w("- `validate_benchmark.py` (independent of the parsers): schema; every listed identifier occurs in its code and passes all core rules of its kind; "
      "`codeContext` equals the dedented excerpt of the pinned source bytes in `corpus/<lang>/<file>.md`; for each violation the original passes and the injected name fails "
      "its rule with the recorded reasons, the rule is retrievable for the kind, `injectionMethod` reproduces, and the two code contexts differ only by original->injected identifier text; indexes match files.\n"
      "- `syntax_check.py`: every snippet and every violated context parses standalone (Python `ast`; others tree-sitter, class members wrapped in a class).\n"
      "- Corpus integrity: every corpus file's git blob SHA-1 recomputed during curation equals `corpus_index.tsv` "
      f"({len(st['index_mismatch'])} mismatches).\n"
      "- Determinism: two full runs produced byte-identical snippets/violations.\n")
    open(os.path.join(B, "curation_report.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print("wrote", os.path.join(B, "curation_report.md"), len("\n".join(L)), "chars")


main()
